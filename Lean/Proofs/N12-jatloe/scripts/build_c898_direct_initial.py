#!/usr/bin/env python3
"""Emit all C898 direct initial covers, without replaying or searching proofs.

The authenticated 704-domain audit is an input check, not a trusted theorem.
Every emitted root proves the independent integer vertex check in Lean. The
emitter stores eight original input indices, derives all forbidden constraints
from actual outside points, and copies the exact original reduced target rows.
No old region forest, raw leaf, or incoming relaxation certificate is imported.

Prepared for the parent's serial compute slot. Explicit --run is required.
Limits: 120 seconds, 256 MiB RSS, 8 MiB total generated Lean source. Does not
start Lean, access the network, modify Complete.lean, or remove any old source.
"""
from collections import Counter
from fractions import Fraction as Q
from pathlib import Path
import argparse
import hashlib
import json
import os
import re
import resource
import signal
import sys
import time

from audit_c898_direct_cover import point_forms, primitive_normal

ROOT = Path(__file__).resolve().parents[1]
DEST = ROOT / 'Compact/Cases/C898/DirectInitial'
OWNERS = {0: 1, 1: 2, 2: 12, 3: 16, 5: 768, 6: 1056,
          7: 2048, 8: 4096, 9: 8192, 10: 16384, 11: 32768}
NAMESPACE = 'N12Compact.C898DirectInitial'


def digest(path):
    h = hashlib.sha256()
    with path.open('rb') as stream:
        for chunk in iter(lambda: stream.read(65536), b''):
            h.update(chunk)
    return h.hexdigest()


def rational(value):
    q = Q(value)
    return str(q.numerator) if q.denominator == 1 else f'({q.numerator}/{q.denominator})'


def point_list(points):
    return '[' + ', '.join(f'({rational(x)}, {rational(y)})' for x, y in points) + ']'


def strongest_original_indices(rows):
    """Select strongest representatives, retaining original coefficients/order.

    Normalization is used only for comparison. The Lean source stores the
    resulting indices into original poseInputs, never the normalized values.
    """
    best = {}
    for index, row in enumerate(rows):
        x, y, c = primitive_normal(row)
        assert x or y
        if (x, y) not in best or c < best[x, y][0]:
            best[x, y] = (c, index)
    return sorted(index for _, index in best.values())


def header(imports, namespace=NAMESPACE):
    return '\n'.join('import ' + name for name in imports) + f'''

/-! Generated by scripts/build_c898_direct_initial.py.
Original geometric inputs and exact reduced outputs; every finite numeric
claim below is independently checked by the ordinary Lean kernel. -/

namespace {namespace}
open S12 S12Pilot DirectPoseCover IntegerSupport
set_option maxRecDepth 100000
set_option maxHeartbeats 0
set_option Elab.async false
set_option linter.unnecessarySeqFocus false

'''


def footer(namespace=NAMESPACE):
    return f'\nend {namespace}\n'


def root_source(owner, angle, indices, target, rows):
    suffix = f'{owner}_{angle}'
    source = []
    if target is not None:
        source.append(f'noncomputable def target{suffix} : List Form := literalForms (row_array%[\n')
        for row_id in target['rows']:
            row = rows[row_id]
            x, y, c = row['integers']
            den = row['denominator']
            assert den > 0
            assert not row['strict'] or (x == y == 0 and c > 0)
            source.append(f'  ({x}, {y}, {c}, {str(row["strict"]).lower()}, {den-1}),\n')
        source.append('])\n\n')
    source.append(f'def indices{suffix} : List (Fin (poseInputs angle64_{angle} inside{owner}).length) :=\n')
    source.append('  [' + ', '.join(f'⟨{i}, by decide +kernel⟩' for i in indices) + ']\n\n')
    result = 'none' if target is None else f'(some target{suffix})'
    source.append(f'''noncomputable def root{suffix} : Root :=
  sourceRoot ⟨angle64_{angle}, angle64_{angle}_checked⟩ inside{owner} outside{owner}
    indices{suffix} {result}

theorem root{suffix}_checked : root{suffix}.Check inside{owner} outside{owner} := by
  unfold root{suffix}
  apply sourceRoot_check
  · unfold PlanarVertex.BoxNormals
    decide +kernel
  · decide +kernel
  · decide +kernel

''')
    return ''.join(source)


def owner_source(owner):
    refs = ',\n    '.join(f'⟨root{owner}_{a}, root{owner}_{a}_checked⟩' for a in range(64))
    return f'''noncomputable def owner{owner} : Owner :=
  ⟨inside{owner}, outside{owner},
   [{refs}]⟩

theorem owner{owner}_checked : owner{owner}.Check :=
  C898Initial.angles64_cover_kernel

'''


def bridge_source(owner, reduced):
    lines = []
    for angle in range(64):
        target = reduced.get((owner, angle))
        expected = '[]' if target is None else f'[C898Shared.poses {target["index"]}]'
        lines.append(f'''/-- Exact target, including row order and original angle enclosure. -/
theorem root{owner}_{angle}_shared : root{owner}_{angle}.leaves = {expected} := by
  rfl

''')
    lines.append(f'''theorem owner{owner}_leaves_shared :
    owner{owner}.leaves = C898Shared.continuousScout898Domain{owner}_0 := by
  unfold Owner.leaves owner{owner}
  simp only [List.flatMap_cons, List.flatMap_nil]
  rw [''')
    lines.append(',\n    '.join(f'root{owner}_{a}_shared' for a in range(64)))
    lines.append(']\n  rfl\n\n')
    lines.append(f'''/-- All continuous orientations, directly in the original reduced domain. -/
theorem owner{owner}_oriented_cover_shared (q : OpenSquare)
    (ha : 1 < q.side) (hs : q.side ≤ 1001 / 1000) (hb : InsideContainer q)
    (hi : ∀ P ∈ inside{owner}, q.Inside P.1 P.2)
    (ho : ∀ P ∈ outside{owner}, ¬q.Inside P.1 P.2) :
    OrientedPoseCovered C898Shared.continuousScout898Domain{owner}_0 q := by
  rw [← owner{owner}_leaves_shared]
  exact owner{owner}.oriented_sound owner{owner}_checked q ha hs hb hi ho

#print axioms owner{owner}_oriented_cover_shared
''')
    return ''.join(lines)


def entry_source():
    namespace = 'N12Compact.C898Entry'
    source = header(['Compact.Bridge.PointPremises', 'Compact.Cases.C898.EntryPoints',
                     'Compact.Cases.C898.DirectInitial.All'], namespace)
    source += 'open C898DirectInitial\n\n'
    for owner, mask in OWNERS.items():
        source += f'''theorem owner{owner}_premises_checked :
    PointPremises.Check case898Domain{owner} commonPoints898 inside{owner} outside{owner} := by
  decide +kernel

/-- Actual packing entrance; no certificate or pose-cover premise remains. -/
theorem owner{owner}_cover (p : NormalizedPacking)
    (hf : codedMarkerFamily p = case898Family) :
    OrientedPoseCovered C898Shared.continuousScout898Domain{owner}_0
      (p.square (ownerIndex p {mask})) := by
  obtain ⟨hi, ho⟩ := PointPremises.sound case898Domain{owner} commonPoints898 inside{owner} outside{owner}
    owner{owner}_premises_checked p hf
  exact owner{owner}_oriented_cover_shared _
    (by rw [p.congruent]; exact p.side_gt_one)
    (by rw [p.congruent]; exact p.side_le) (p.contained _) hi ho

'''
    return source + footer(namespace)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--run', action='store_true')
    args = parser.parse_args()
    if not args.run:
        parser.error('Source prepared only; --run requires the parent serial compute slot.')
    started = time.monotonic()

    def guard(*_):
        rss = resource.getrusage(resource.RUSAGE_SELF).ru_maxrss
        if sys.platform != 'darwin':
            rss *= 1024
        if time.monotonic() - started > 120 or rss > 256 * 1024**2:
            raise RuntimeError('Direct initial emitter exceeded 120 seconds or 256 MiB RSS')

    signal.signal(signal.SIGALRM, guard)
    signal.setitimer(signal.ITIMER_REAL, 0.1, 0.1)
    paths = {name: ROOT / path for name, path in {
        'geometry': 'evidence/C898/raw/data/region898.json',
        'poses': 'evidence/c898-shared-pose-map.json',
        'angles': 'vendor/S12/AngleData.lean',
    }.items()}
    audit = json.loads((ROOT / 'evidence/c898-direct-cover-all.json').read_text())
    assert audit['counts']['owner_angles'] == 704
    assert audit['counts']['absent_pose_angles'] == 74
    assert audit['counts']['absent_pose_closed_nonempty'] == 0
    assert audit['counts']['target_failures'] == 0 and not audit['failures']
    hashes = {name: digest(path) for name, path in paths.items()}
    assert hashes == audit['input_sha256'], 'Audit inputs changed; rerun independent audit first'
    raw = json.loads(paths['geometry'].read_text())
    owners = {record['owner']: {key: record[key] for key in ('inside', 'outside')}
              for record in raw}
    del raw
    assert set(owners) == set(OWNERS)
    angles = {int(i): [Q(x.strip().strip('()')) for x in values.split(',')]
              for i, values in re.findall(r'def angle64_(\d+) : AngleEnclosure := ⟨([^⟩]+)⟩',
                                          paths['angles'].read_text())}
    assert set(angles) == set(range(64))
    pose_map = json.loads(paths['poses'].read_text())
    reduced = {}
    for pose in pose_map['poses']:
        matched = re.fullmatch(r'continuousScout898Initial(\d+)_(\d+)', pose['name'])
        if matched:
            key = int(matched[1]), pose['angle']
            assert key not in reduced
            reduced[key] = pose
    assert len(reduced) == 630
    domains = json.loads((ROOT / 'evidence/c898-domain-map.json').read_text())['domains']
    audited = {(item['owner'], item['angle']): item for item in audit['cases']}
    assert len(audited) == 704
    outputs = {}
    counts = Counter()
    unique_target_row_ids = set()
    mapping = []
    inputs = header(['Compact.Bridge.DirectPoseForms', 'Compact.Core.RowSyntax',
                     'Compact.Cases.C898.Initial.Angles'])
    inputs += '''/-- Typed literal rows remain local to a root's finite check. -/
def literalForms (data : Array (Row × Nat)) : List Form :=
  data.toList.map (fun pair => ⟨pair.1, pair.2⟩)

'''
    for owner, record in owners.items():
        inputs += f'def inside{owner} : List (ℚ × ℚ) := {point_list(record["inside"])}\n'
        inputs += f'def outside{owner} : List (ℚ × ℚ) := {point_list(record["outside"])}\n\n'
    outputs['Inputs.lean'] = inputs + footer()
    pilot = header(['Compact.Cases.C898.DirectInitial.Inputs'])
    for owner in OWNERS:
        imports = ['Compact.Cases.C898.DirectInitial.' + ('Pilot' if owner == 0 else 'Inputs')]
        data_source = header(imports)
        expected_ids = []
        for angle in range(64):
            _, _, c, s, outer, _, wall = angles[angle]
            original = [row for point in owners[owner]['inside']
                        for row in point_forms(c, s, Q(1001, 1000) * outer, point)]
            wall_start = len(original)
            original += [(Q(1), Q(0), -wall/2), (Q(-1), Q(0), 4-wall/2),
                         (Q(0), Q(1), -wall/2), (Q(0), Q(-1), 4-wall/2)]
            indices = strongest_original_indices(original)
            assert len(indices) == 8
            assert all(i in indices for i in range(wall_start, wall_start+4))
            assert all(0 <= i < len(original) for i in indices)
            target = reduced.get((owner, angle))
            old = audited[owner, angle]
            assert old['target_pose'] == (None if target is None else target['name'])
            assert old['base_planes'] == len(indices)
            if target is not None:
                expected_ids.append(target['index'])
                counts['target_row_records'] += len(target['rows'])
                unique_target_row_ids.update(target['rows'])
            else:
                assert old['closed_empty']
            emitted = root_source(owner, angle, indices, target, pose_map['rows'])
            if owner == angle == 0:
                pilot += emitted
            else:
                data_source += emitted
            counts['root_certificates'] += 1
            counts['selected_input_indices'] += len(indices)
            counts['forbidden_rows_derived_not_stored'] += 4 * len(owners[owner]['outside'])
            counts['base_rows_derived_not_stored'] += len(indices)
            mapping.append({'owner': owner, 'angle': angle, 'input_indices': indices,
                            'target_name': None if target is None else target['name'],
                            'target_id': None if target is None else target['index']})
        assert expected_ids == domains[f'continuousScout898Domain{owner}_0'], 'Exact domain order changed'
        data_source += owner_source(owner)
        outputs[f'Data{owner:02d}.lean'] = data_source + footer()
        outputs[f'Owner{owner:02d}.lean'] = header([
            f'Compact.Cases.C898.DirectInitial.Data{owner:02d}',
            'Compact.Cases.C898.SharedDomains']) + bridge_source(owner, reduced) + footer()
    outputs['Pilot.lean'] = pilot + '#print axioms root0_0_checked\n' + footer()
    outputs['All.lean'] = '\n'.join(f'import Compact.Cases.C898.DirectInitial.Owner{i:02d}'
                                    for i in OWNERS) + '\n'
    outputs['Entry.lean'] = entry_source()
    total_bytes = sum(len(source.encode()) for source in outputs.values())
    assert total_bytes < 8 * 1024**2
    assert counts['root_certificates'] == 704
    counts['unique_shared_target_rows'] = len(unique_target_row_ids)
    guard()
    DEST.mkdir(parents=True, exist_ok=True)
    temporary = []
    try:
        for name, source in outputs.items():
            path = DEST / name
            temp = path.with_suffix('.lean.tmp')
            temporary.append(temp)
            temp.write_text(source)
            os.replace(temp, path)
        report = {
            'scope': 'Complete source assembly; generated certificates and owner bridges still require Lean replay.',
            'counts': dict(counts), 'owner_count': 11, 'reduced_pose_count': 630,
            'empty_angle_count': 74, 'generated_module_count': len(outputs),
            'generated_lean_bytes': total_bytes,
            'generated_lean_lines': sum(source.count('\n') for source in outputs.values()),
            'input_sha256': hashes,
            'audit_sha256': digest(ROOT / 'evidence/c898-direct-cover-all.json'),
            'generator_sha256': digest(Path(__file__)),
            'files': {str((DEST / name).relative_to(ROOT)): {
                'sha256': hashlib.sha256(source.encode()).hexdigest(),
                'bytes': len(source.encode()), 'lines': source.count('\n')}
                for name, source in outputs.items()},
            'roots': mapping,
            'elapsed_seconds': time.monotonic() - started,
            'integration': 'Replace Complete import Incoming with Compact.Cases.C898.DirectInitial.Entry after replay.',
            'checks': ['704 audit-input hashes matched', '630 exact target row sequences preserved',
                       '74 absent target intervals retained and checked empty',
                       '11 complete original reduced domain ID orders matched',
                       'all64 original angles retained for every owner',
                       'original constraint indices only; forbidden blocks derived without normalization'],
        }
        report_path = ROOT / 'evidence/c898-direct-initial-source.json'
        temp = report_path.with_suffix('.json.tmp')
        temporary.append(temp)
        temp.write_text(json.dumps(report, separators=(',', ':')) + '\n')
        os.replace(temp, report_path)
    finally:
        signal.setitimer(signal.ITIMER_REAL, 0)
        for temp in temporary:
            if temp.exists():
                temp.unlink()
    print(json.dumps({key: report[key] for key in (
        'counts', 'generated_module_count', 'generated_lean_bytes', 'generated_lean_lines', 'elapsed_seconds')}))


if __name__ == '__main__':
    main()
